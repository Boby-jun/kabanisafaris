/* Shows the gold "New" badge next to Field Notes for 48 hours after a new article goes live.
   Generated by the blog builder (NEW_BADGE_FROM). */
(function () {
  var from = Date.parse("2026-11-10T22:00:00+01:00");
  var age = Date.now() - from;
  if (isNaN(from) || age < 0 || age >= 48 * 60 * 60 * 1000) return;
  var els = document.querySelectorAll('.nav-badge .nav-new');
  for (var i = 0; i < els.length; i++) els[i].hidden = false;
})();
